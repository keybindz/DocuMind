"""
Storage backend abstraction.

Phase 1 uses local disk so the whole stack runs with just Postgres + the API
container — no extra infra to stand up. Every document row still stores a
`storage_path` in the same shape an S3 key would take
(`{tenant_id}/{document_id}_{filename}`), so swapping in an S3/MinIO-backed
implementation later is a one-class change, not a schema migration.
"""
import abc
import os
import uuid
from pathlib import Path

from app.config import get_settings

settings = get_settings()


class StorageBackend(abc.ABC):
    @abc.abstractmethod
    def save(self, *, tenant_id: uuid.UUID, document_id: uuid.UUID, filename: str, content: bytes) -> str:
        """Persist file content, return a storage_path/key."""

    @abc.abstractmethod
    def read(self, storage_path: str) -> bytes:
        """Read file content back by storage_path/key."""

    @abc.abstractmethod
    def delete(self, storage_path: str) -> None:
        """Delete the underlying file. Should not raise if already missing."""


class LocalDiskStorage(StorageBackend):
    def __init__(self, base_dir: str | None = None):
        self.base_dir = Path(base_dir or settings.STORAGE_DIR)
        self.base_dir.mkdir(parents=True, exist_ok=True)

    def _full_path(self, storage_path: str) -> Path:
        # storage_path is always relative and generated by us (never user input),
        # so this is safe from path traversal.
        return self.base_dir / storage_path

    def save(self, *, tenant_id: uuid.UUID, document_id: uuid.UUID, filename: str, content: bytes) -> str:
        safe_filename = os.path.basename(filename)
        relative_path = f"{tenant_id}/{document_id}_{safe_filename}"
        full_path = self._full_path(relative_path)
        full_path.parent.mkdir(parents=True, exist_ok=True)
        full_path.write_bytes(content)
        return relative_path

    def read(self, storage_path: str) -> bytes:
        return self._full_path(storage_path).read_bytes()

    def delete(self, storage_path: str) -> None:
        full_path = self._full_path(storage_path)
        full_path.unlink(missing_ok=True)


_default_backend: StorageBackend | None = None


def get_storage_backend() -> StorageBackend:
    global _default_backend
    if _default_backend is None:
        _default_backend = LocalDiskStorage()
    return _default_backend
